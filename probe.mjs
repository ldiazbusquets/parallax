import { chromium } from 'playwright';
const B = 'https://ldiazbusquets.github.io/parallax/';
const br = await chromium.launch(); const p = await br.newPage({ viewport: { width: 1300, height: 900 } });
await p.goto(B + '?v=' + Date.now() + '#/w/geo'); await p.waitForTimeout(12000);
await p.locator('#p-map').getByText(/^Shipping/).first().click(); await p.locator('#p-map').getByText(/^Events/).first().click();
await p.locator('#p-map').locator('.maplibregl-ctrl-zoom-out, [aria-label="Zoom out"]').first().click().catch(() => {}); await p.waitForTimeout(800);
await p.locator('#p-map').locator('.maplibregl-ctrl-zoom-out, [aria-label="Zoom out"]').first().click().catch(() => {}); await p.waitForTimeout(800);
await p.locator('#p-map').getByText(/^Cargo/).first().click(); await p.waitForTimeout(6000);
console.log('dots', await p.locator('.mk').count());
await p.locator('#p-map').screenshot({ path: 'shots/world-cargo.png' });
await br.close();
